#  Adjust Features (Feature Selection)
X_new = X_new.drop(['children', 'sex', 'bmi'], axis = 1)

# Explore new Dataset
print("\n" + "="*50)
print("===== 4. Data After Feature Engineering =====")
print("="*50)
print("\n--- First 5 Rows of the New Feature Set (X_new) ---")
print(X_new.head())

# Split Dataset
X_train1, X_test1, y_train1, y_test1 = train_test_split(X_new, y, test_size=0.2, random_state=42)

# Train the Linear Regression Model
model = LinearRegression()
model.fit(X_train1, y_train1)

# Make Predictions
y_pred1 = model.predict(X_test1)

# Evaluate the model
print("\n" + "="*50)
print("===== 5. Refined Model Performance =====")
print("="*50)
mse2 = mean_squared_error(y_test1, y_pred1)
