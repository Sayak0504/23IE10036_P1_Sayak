rmse1 = np.sqrt(mse1)

print(f"Mean Squared Error: {mse1:.2f}")
print(f"R-squared: {r2_1:.4f}")
print(f"Root Mean Squared Error (RMSE): ${rmse1:.2f}")

# Analyze Model Coefficients
print("\n--- Initial Model Coefficients ---")
coefficients1 = pd.DataFrame(model.coef_, X.columns, columns=['Coefficient'])
print(coefficients1)

############ Model Refinement ############
X_new = X

# Add Interaction Terms
X_new['bmi_smoker'] = X_new['bmi'] * X_new['smoker']
